#!/usr/bin/env bash
set -Eeuo pipefail
# Writes the cluster-specific (non-secret) values from `terraform output` into the files the Helm chart
# and Argo CD read. Re-run it after every apply that changes them, then commit the two files:
#   gitops/values/cluster.yaml                       registry, RDS secret ARN, backup bucket, certificate
#   gitops/values/aws-load-balancer-controller.yaml  cluster name, region, VPC ID
# Usage: scripts/configure-from-terraform.sh [terraform-root]   (default infra/terraform/envs/staging)
trap 'echo "configure-from-terraform.sh: error on line $LINENO" >&2' ERR

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
TF_DIR=${1:-infra/terraform/envs/staging}
command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }

out=$(terraform -chdir="$ROOT/$TF_DIR" output -json)
get() { jq -er "$1" <<<"$out"; }

registry=$(get .ecr_registry.value)
region=$(get .region.value)
cluster=$(get .cluster_name.value)
vpc=$(get .vpc_id.value)
rds_secret=$(get .rds_master_secret_arn.value)
bucket=$(get .backup_bucket.value)
cert=$(jq -r '.acm_certificate_arn.value // ""' <<<"$out")

cat >"$ROOT/gitops/values/cluster.yaml" <<EOF
# GENERATED by scripts/configure-from-terraform.sh from \`terraform output\`: do not edit by hand.
# Cluster-specific, non-secret values shared by Helm (make helm-install) and both Argo CD apps.
image:
  registry: $registry
secrets:
  dbMasterSecretArn: "$rds_secret"
  dbParameterPrefix: /africair/staging/db
ingress:
  certificateArn: "$cert"
backup:
  bucket: $bucket
EOF

cat >"$ROOT/gitops/values/aws-load-balancer-controller.yaml" <<EOF
# GENERATED by scripts/configure-from-terraform.sh from \`terraform output\`: do not edit by hand.
clusterName: $cluster
region: $region          # passed explicitly: IMDS hop limit 1 hides the instance metadata from pods
vpcId: $vpc
replicaCount: 2
serviceAccount:
  create: true
  name: aws-load-balancer-controller
EOF

echo "wrote gitops/values/cluster.yaml and gitops/values/aws-load-balancer-controller.yaml"
echo "commit them so Argo CD sees them: git add gitops/values && git commit -m 'gitops: cluster values' && git push"
